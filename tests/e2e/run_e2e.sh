#!/bin/bash
# End-to-end test harness for DCD: builds a test hub with a writable
# config directory, starts it, runs the Python NMDC test suite, stops it.
set -u

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
E2E_DIR="${DCD_E2E_DIR:-/tmp/dcd-e2e}"
PORT="${DCD_E2E_PORT:-41111}"
CONS_PORT=$((PORT + 400))
PREFIX="$E2E_DIR/prefix"
CONF="$PREFIX/etc/dcd"

fail() { echo "E2E SETUP FAILURE: $*" >&2; exit 2; }

echo "== building test hub (CONFIGDIR=$CONF) =="
cmake -S "$ROOT" -B "$E2E_DIR/build" \
      -DCMAKE_INSTALL_PREFIX="$PREFIX" \
      -DCMAKE_BUILD_TYPE=Release > "$E2E_DIR-cmake.log" 2>&1 \
  || fail "cmake configure failed (see $E2E_DIR-cmake.log)"
cmake --build "$E2E_DIR/build" >> "$E2E_DIR-cmake.log" 2>&1 \
  || fail "build failed (see $E2E_DIR-cmake.log)"
cmake --install "$E2E_DIR/build" >> "$E2E_DIR-cmake.log" 2>&1 \
  || fail "install failed (see $E2E_DIR-cmake.log)"

echo "== writing test configuration =="
cat > "$CONF/dcd.conf" <<EOF
# generated by tests/e2e/run_e2e.sh -- do not edit
bind_address = 127.0.0.1
listen_port_main = $PORT
listen_port_cons = $CONS_PORT
n_listen_main = 1
n_user_manager = 1
hubname = E2E-Test-Hub
user_limit = 100
allow_chat = 1
allow_passive = 1
allow_forwarding = 0
allow_downloads = 1
allow_search = 1
registered_only = 0
search_interval = 0
min_share = 0
min_slots = 0
idle_timeout = 10
register_timeout = 30
EOF

cat > "$CONF/dcd.users" <<'EOF'
testop:secret:testop@example.com:E2E operator:sc
EOF

cat > "$CONF/dcd.welcome" <<'EOF'
Welcome to the E2E test hub.
EOF

cat > "$CONF/console.allow" <<'EOF'
127.0.0.1
EOF

cat > "$CONF/nicks.allow" <<'EOF'
*
EOF

: > "$CONF/dcd.banned"
: > "$CONF/dcd.penalties"
: > "$CONF/dcd.hublinks"
: > "$CONF/dcd.motd"
: > "$CONF/dcd.rules"
: > "$CONF/dcd.usercommands"

echo "== starting hub on port $PORT (console $CONS_PORT) =="
pkill -f "$PREFIX/sbin/dcd" 2>/dev/null
sleep 0.2
"$PREFIX/sbin/dcd" || fail "dcd exited immediately"

HUB_PID=""
for i in $(seq 1 50); do
  if python3 - "$PORT" <<'EOF'
import socket, sys
s = socket.socket()
try:
    s.connect(("127.0.0.1", int(sys.argv[1])))
except OSError:
    sys.exit(1)
s.close()
EOF
  then HUB_PID="$(pgrep -f "$PREFIX/sbin/dcd" | head -1)"; break; fi
  sleep 0.1
done
[ -n "$HUB_PID" ] || fail "hub did not start listening on $PORT"
echo "hub pid $HUB_PID"

echo "== running E2E suite =="
python3 "$ROOT/tests/e2e/test_e2e.py" --port "$PORT" --cons-port "$CONS_PORT"
RC=$?

echo "== stopping hub =="
kill -TERM "$HUB_PID" 2>/dev/null
for i in $(seq 1 30); do kill -0 "$HUB_PID" 2>/dev/null || break; sleep 0.1; done
kill -0 "$HUB_PID" 2>/dev/null && { echo "hub did not stop on SIGTERM"; kill -KILL "$HUB_PID"; }

if [ $RC -eq 0 ]; then echo "E2E: PASS"; else echo "E2E: FAIL (rc=$RC)"; fi
exit $RC
